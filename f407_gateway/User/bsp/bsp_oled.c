/* ---- I2C 底层 (HAL 硬件 I2C 替换江协科技的软件 GPIO 模拟) ---- */
/* 诊断性延时: 江协科技软件模拟 I2C 字节间天然有 GPIO 翻转延时(慢),
   本模块在 F407 硬件 I2C 100kHz 下偶发位翻转(满屏FF测试掩盖, 字符暴露)。
   每次事务后加 1ms, 给 SSD1306 处理时间 + 保证 tBUF 总线空闲, 验证是否时序问题。
   确认有效后再优化: 改微秒级延时 / 仅命令后加 / 或 CubeMX 降 50kHz。 */
static void oled_write_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};   /* 0x00 = Co=0, D/C#=0 (命令) */
    if (BSP_I2C1_Write(OLED_ADDR, buf, 2) != HAL_OK) s_i2c_err++;
    HAL_Delay(1);
}

static void oled_write_data(uint8_t data)
{
    uint8_t buf[2] = {0x40, data};  /* 0x40 = Co=0, D/C#=1 (数据) */
    if (BSP_I2C1_Write(OLED_ADDR, buf, 2) != HAL_OK) s_i2c_err++;
    /* 数据流水: 满屏FF测试已证明 SSD1306 接得住连续数据, 不加延时保持快 */
}

